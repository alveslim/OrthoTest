-- OrtoCheck · schema base (ORT-06, ORT-07, ORT-09)
-- Datas em TIMESTAMPTZ; exclusão lógica (excluido_em); FKs com ON DELETE RESTRICT.
-- status/progresso da avaliação são CALCULADOS por trigger (ninguém grava à mão).

-- ============================================================ perfis
CREATE TABLE IF NOT EXISTS public.perfis (
  user_id        UUID PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  nome_exibicao  TEXT NOT NULL CHECK (length(trim(nome_exibicao)) > 0),
  papel          TEXT NOT NULL DEFAULT 'aluno' CHECK (papel IN ('aluno', 'professor')),
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================ catálogo
-- Novos testes entram só com INSERT aqui (ORT-45), sem mexer em código.
CREATE TABLE IF NOT EXISTS public.testes_catalogo (
  id             SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  regiao         VARCHAR(50)  NOT NULL,
  nome           VARCHAR(100) NOT NULL,
  estrutura      VARCHAR(150),
  definicao      TEXT NOT NULL,
  objetivo       TEXT NOT NULL,
  como_fazer     TEXT NOT NULL,
  positivo_se    TEXT NOT NULL,
  unidade_medida VARCHAR(20),          -- ex.: 'graus' (Lasègue). NULL = sem valor medido
  referencia     TEXT,                 -- NULL até haver fonte bibliográfica verificada
  ativo          BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT teste_unico_por_regiao UNIQUE (regiao, nome)
);

-- ============================================================ participantes
-- Sem nome completo: identificado só por código (P-001), único POR avaliador.
CREATE TABLE IF NOT EXISTS public.participantes (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id            UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users (id) ON DELETE RESTRICT,
  codigo             VARCHAR(20)  NOT NULL,
  idade              SMALLINT     NOT NULL CHECK (idade > 0 AND idade < 120),
  peso_kg            NUMERIC(5,2) CHECK (peso_kg > 0 AND peso_kg < 400),
  altura_m           NUMERIC(3,2) CHECK (altura_m BETWEEN 0.5 AND 2.5),
  consentimento      BOOLEAN      NOT NULL DEFAULT FALSE,
  data_consentimento TIMESTAMPTZ,
  criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
  excluido_em        TIMESTAMPTZ,
  CONSTRAINT consentimento_exige_data CHECK (consentimento = FALSE OR data_consentimento IS NOT NULL),
  CONSTRAINT codigo_unico_por_avaliador UNIQUE (user_id, codigo)
);

-- ============================================================ avaliações
CREATE TABLE IF NOT EXISTS public.avaliacoes (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  participante_id      UUID NOT NULL REFERENCES public.participantes (id) ON DELETE RESTRICT,
  avaliador_id         UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users (id) ON DELETE RESTRICT,
  data_avaliacao       TIMESTAMPTZ NOT NULL DEFAULT now(),
  flag_professor       BOOLEAN NOT NULL DEFAULT FALSE,
  flag_motivo          TEXT,
  status               TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'em_andamento', 'concluido')),
  progresso_percentual NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (progresso_percentual BETWEEN 0 AND 100),
  excluido_em          TIMESTAMPTZ
);
-- Uma avaliação ativa por participante.
CREATE UNIQUE INDEX IF NOT EXISTS uq_avaliacao_ativa_por_participante
  ON public.avaliacoes (participante_id) WHERE excluido_em IS NULL;

-- ============================================================ resultados
CREATE TABLE IF NOT EXISTS public.resultados_testes (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  avaliacao_id UUID        NOT NULL REFERENCES public.avaliacoes (id)      ON DELETE RESTRICT,
  teste_id     SMALLINT    NOT NULL REFERENCES public.testes_catalogo (id) ON DELETE RESTRICT,
  lado         VARCHAR(10) NOT NULL CHECK (lado IN ('Direito', 'Esquerdo', 'Bilateral')),
  resultado    VARCHAR(15) NOT NULL CHECK (resultado IN ('Positivo', 'Negativo', 'Não realizado', 'Inconclusivo')),
  valor_medido NUMERIC(5,1),
  dor_0_10     SMALLINT    CHECK (dor_0_10 BETWEEN 0 AND 10),
  observacoes  TEXT CHECK (observacoes IS NULL OR length(observacoes) <= 500),
  criado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
  excluido_em  TIMESTAMPTZ,
  CONSTRAINT resultado_unico_por_lado UNIQUE (avaliacao_id, teste_id, lado)
);

-- ============================================================ rascunhos da IA
CREATE TABLE IF NOT EXISTS public.ia_rascunhos (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  avaliacao_id UUID        NOT NULL REFERENCES public.avaliacoes (id) ON DELETE RESTRICT,
  texto        TEXT        NOT NULL CHECK (length(trim(texto)) > 0),
  gerado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
  revisado_por UUID        REFERENCES auth.users (id) ON DELETE RESTRICT,
  aprovado     BOOLEAN     NOT NULL DEFAULT FALSE,
  CONSTRAINT aprovado_exige_revisor CHECK (aprovado = FALSE OR revisado_por IS NOT NULL)
);

-- ============================================================ índices das FKs
CREATE INDEX IF NOT EXISTS idx_participantes_user      ON public.participantes (user_id);
CREATE INDEX IF NOT EXISTS idx_avaliacoes_avaliador    ON public.avaliacoes (avaliador_id);
CREATE INDEX IF NOT EXISTS idx_resultados_teste        ON public.resultados_testes (teste_id);
CREATE INDEX IF NOT EXISTS idx_ia_rascunhos_avaliacao  ON public.ia_rascunhos (avaliacao_id);
CREATE INDEX IF NOT EXISTS idx_ia_rascunhos_revisor    ON public.ia_rascunhos (revisado_por);

-- ============================================================ progresso calculado
CREATE OR REPLACE FUNCTION public.recalcular_progresso(p_avaliacao UUID)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  total  INT;
  feitos INT;
BEGIN
  SELECT count(*) INTO total FROM testes_catalogo WHERE ativo;
  -- Conta TESTES distintos com resultado (qualquer lado). "Não realizado" e "Inconclusivo" contam.
  SELECT count(DISTINCT r.teste_id) INTO feitos
    FROM resultados_testes r
    JOIN testes_catalogo t ON t.id = r.teste_id AND t.ativo
   WHERE r.avaliacao_id = p_avaliacao AND r.excluido_em IS NULL;

  UPDATE avaliacoes
     SET progresso_percentual = CASE WHEN total > 0 THEN round(feitos * 100.0 / total, 2) ELSE 0 END,
         status = CASE WHEN feitos = 0 THEN 'pendente'
                       WHEN total > 0 AND feitos >= total THEN 'concluido'
                       ELSE 'em_andamento' END
   WHERE id = p_avaliacao;
END $$;

CREATE OR REPLACE FUNCTION public.trg_resultados_progresso()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  PERFORM public.recalcular_progresso(COALESCE(NEW.avaliacao_id, OLD.avaliacao_id));
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS resultados_progresso ON public.resultados_testes;
CREATE TRIGGER resultados_progresso
  AFTER INSERT OR UPDATE OR DELETE ON public.resultados_testes
  FOR EACH ROW EXECUTE FUNCTION public.trg_resultados_progresso();

-- ============================================================ perfil automático no cadastro
CREATE OR REPLACE FUNCTION public.criar_perfil_novo_usuario()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.perfis (user_id, nome_exibicao, papel)
  VALUES (NEW.id,
          COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'nome', ''), split_part(COALESCE(NEW.email, 'usuario'), '@', 1)),
          'aluno')
  ON CONFLICT (user_id) DO NOTHING;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.criar_perfil_novo_usuario();

-- Funções internas: ninguém chama pela API.
REVOKE EXECUTE ON FUNCTION public.recalcular_progresso(UUID)   FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.trg_resultados_progresso()   FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.criar_perfil_novo_usuario()  FROM PUBLIC, anon, authenticated;
